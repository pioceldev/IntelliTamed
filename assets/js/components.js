  function esc(str) {
    return String(str).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  function icon(name, cls) {
    var c = cls ? " class=\"" + esc(cls) + "\"" : "";
    return "<span" + c + " aria-hidden=\"true\">" + (ICONS[name] || "") + "</span>";
  }

